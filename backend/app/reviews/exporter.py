from __future__ import annotations

from typing import Any


def export_to_markdown(
    review: dict[str, Any], sections: list[dict[str, Any]], matrix: list[dict[str, Any]]
) -> str:
    lines = [
        f"# {review.get('title', 'Literature Review')}",
        "",
        review.get("description") or "",
        "",
        "---",
        "",
    ]

    for sec in sections:
        sec_type = sec.get("section_type", "").replace("_", " ").title()
        lines.append(f"## {sec_type}")
        if sec.get("is_abstract_only"):
            lines.append("*(Synthesized from paper abstracts)*")
            lines.append("")
        lines.append(sec.get("content") or "No content generated yet.")
        lines.append("")

    if matrix:
        lines.append("## Comparative Matrix")
        lines.append("")
        lines.append("| Paper | Year | Research Problem | Methodology | Dataset |")
        lines.append("| :--- | :--- | :--- | :--- | :--- |")
        for row in matrix:
            t = row.get("title", "").replace("|", "-")
            y = row.get("year") or "—"
            p = row.get("research_problem", "").replace("|", "-").replace("\n", " ")
            m = row.get("methodology", "").replace("|", "-")
            d = row.get("dataset", "").replace("|", "-")
            lines.append(f"| {t} | {y} | {p} | {m} | {d} |")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by PaperTrail Literature Review Studio.*")
    return "\n".join(lines)
